"""Вспомогательные функции приложения tours."""

from django.utils.text import slugify

# Таблица транслитерации по ГОСТ 7.79-2000 (упрощённая, система Б).
TRANSLIT_MAP = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "j", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "shh",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def transliterate(text):
    """Переводит кириллические символы строки в латинские."""
    result = []
    for char in text.lower():
        result.append(TRANSLIT_MAP.get(char, char))
    return "".join(result)


def slugify_ru(text):
    """
    Формирует идентификатор для адреса из русского названия.

    Стандартный slugify отбрасывает кириллицу, а вариант с allow_unicode
    даёт адрес, который не проходит через конвертер slug в маршрутах.
    Поэтому строка сначала транслитерируется.
    """
    return slugify(transliterate(text))
